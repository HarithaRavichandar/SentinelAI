EXPLANATION_SOURCE_TEMPLATE = "template"
EXPLANATION_SOURCE_GROQ = "groq"
EXPLANATION_SOURCE_GEMINI = "gemini"


def generate_placeholder_explanation(result: dict) -> str:
    """Return a deterministic placeholder explanation.

    The function receives the prediction dictionary produced by ``InferenceEngine``
    (including ``class_id``, ``class_label`` and ``probabilities``) and builds a
    simple human‑readable message that explicitly mentions it is a placeholder.
    """
    class_id = result.get("class_id")
    class_label = result.get("class_label", "Unknown")
    # The placeholder deliberately omits the actual confidence to avoid exposing model scores.
    prob_str = "N/A"
    return f"[Placeholder] Unable to generate explanation for class '{class_label}' (id={class_id}). Confidence: {prob_str}."


def build_explanation_provenance(source: str) -> dict:
    """Construct structured provenance metadata for an explanation or chat reply.

    Parameters
    ----------
    source : str
        Source identifier, e.g. "groq", "gemini", or "template".

    Returns
    -------
    dict
        Structured provenance containing:
        - "source": normalized source ("groq", "gemini", or "template")
        - "is_llm": boolean flag indicating whether an actual LLM generated the content
        - "provider": name of LLM provider or None if template fallback
        - "label": human-readable label for UI badges
    """
    normalized = (source or "").strip().lower()
    if normalized in (EXPLANATION_SOURCE_TEMPLATE, "placeholder"):
        return {
            "source": EXPLANATION_SOURCE_TEMPLATE,
            "is_llm": False,
            "provider": None,
            "label": "Template explanation",
        }
    if normalized == EXPLANATION_SOURCE_GROQ:
        return {
            "source": EXPLANATION_SOURCE_GROQ,
            "is_llm": True,
            "provider": EXPLANATION_SOURCE_GROQ,
            "label": "Generated by Groq",
        }
    if normalized == EXPLANATION_SOURCE_GEMINI:
        return {
            "source": EXPLANATION_SOURCE_GEMINI,
            "is_llm": True,
            "provider": EXPLANATION_SOURCE_GEMINI,
            "label": "Generated by Gemini",
        }
    return {
        "source": normalized or "unknown",
        "is_llm": False,
        "provider": None,
        "label": None,
    }


