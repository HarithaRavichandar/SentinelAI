import React, { useState, useEffect, useRef } from 'react';
import { postChat } from '../api';
import LoadingSpinner from './LoadingSpinner';
import ErrorMessage from './ErrorMessage';
import ReactMarkdown from 'react-markdown';
import remarkGfm from 'remark-gfm';

function ChatView() {
  const [message, setMessage] = useState('');
  const [history, setHistory] = useState<any[]>([]);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const chatEndRef = useRef<HTMLDivElement>(null);

  const handleSend = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!message.trim()) return;
    setLoading(true);
    setError(null);
    try {
      const res = await postChat(message, history);
      // Append user and assistant messages to history for next turn
      const newHistory = [...history, { role: 'user', content: message }];
      if (res.reply) {
        newHistory.push({
          role: 'assistant',
          content: res.reply,
          source: res.source,
          provenance: res.provenance,
        });
      }
      setHistory(newHistory);
      setMessage('');
    } catch (err: any) {
      setError(err.message);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    if (chatEndRef.current) {
      chatEndRef.current.scrollIntoView({ behavior: 'smooth' });
    }
  }, [history]);

  return (
    <div className="chat-page">
      <h1 className="text-2xl mb-4 font-medium">Laya Chat</h1>
      <div className="chat-history">
        {history.length === 0 && (
          <div className="chat-welcome">
            <div>
              <p style={{ fontSize: '2rem', marginBottom: '0.5rem' }}>💬</p>
              <p>Ask Laya anything about network security, threat analysis, or SentinelAI.</p>
              <p className="text-sm mt-2" style={{ color: '#555' }}>Your conversation will appear here.</p>
            </div>
          </div>
        )}
        {history.map((msg, idx) => (
          <div key={idx} className={`chat-bubble ${msg.role === 'assistant' ? 'assistant' : 'user'}`}>
            {msg.role === 'assistant' ? (
              <div className="markdown-body">
                <ReactMarkdown remarkPlugins={[remarkGfm]}>{msg.content}</ReactMarkdown>
                {(() => {
                  const src = msg.provenance?.source || msg.source;
                  if (src === 'groq') {
                    return (
                      <div className="mt-2">
                        <span className="inline-block px-2.5 py-0.5 rounded text-xs font-medium bg-emerald-950/80 text-emerald-300 border border-emerald-800">
                          Generated by Groq
                        </span>
                      </div>
                    );
                  }
                  if (src === 'gemini') {
                    return (
                      <div className="mt-2">
                        <span className="inline-block px-2.5 py-0.5 rounded text-xs font-medium bg-blue-950/80 text-blue-300 border border-blue-800">
                          Generated by Gemini
                        </span>
                      </div>
                    );
                  }
                  if (src === 'template' || src === 'placeholder') {
                    return (
                      <div className="mt-2">
                        <span className="inline-block px-2.5 py-0.5 rounded text-xs font-medium bg-zinc-800 text-zinc-400 border border-zinc-700">
                          Template explanation
                        </span>
                      </div>
                    );
                  }
                  return null;
                })()}
              </div>
            ) : (
              msg.content
            )}
          </div>
        ))}
        <div ref={chatEndRef} />
      </div>
      <div className="chat-composer">
        <form onSubmit={handleSend} style={{ display: 'flex', gap: '0.5rem', width: '100%', alignItems: 'flex-start' }}>
          <textarea
            rows={2}
            value={message}
            onChange={(e) => setMessage(e.target.value)}
            placeholder="Type your message…"
            className="resize-none"
            onKeyDown={(e) => {
              if (e.key === 'Enter' && !e.shiftKey) {
                e.preventDefault();
                handleSend(e);
              }
            }}
          />
          <button type="submit" disabled={loading}>Send</button>
        </form>
      </div>
      {loading && <LoadingSpinner />}
      {error && <ErrorMessage message={error} />}
    </div>
  );
}

export default ChatView;
