# scripts/inspect_features.py
"""Feature inspection and preprocessing design generation for SentinelAI (Phase 2).

This script performs a read‑only analysis of the raw feature matrix (Data.csv),
labels (Label.csv), and the split masks generated by Phase 1.  It validates
row‑alignment, mask integrity, and computes a comprehensive set of diagnostics:

* Data types, missing / infinite values
* Constant and near‑constant features
* Unique value counts and basic descriptive statistics
* Extreme (min/max) values per feature
* Highly correlated feature pairs (absolute Pearson > 0.95)
* Feature‑name hygiene checks (identifiers, potential leakage)
* Conflicting‑label duplicate groups (using the same logic as `split.py`)

The results are written to `reports/feature_analysis.md`.  No data is modified
and no model training is performed.
"""

from __future__ import annotations

import pathlib
import sys
from collections import Counter
from typing import List, Tuple

import numpy as np
import pandas as pd

# ---------------------------------------------------------------------------
# Helper utilities
# ---------------------------------------------------------------------------

def load_data(data_path: pathlib.Path, label_path: pathlib.Path) -> Tuple[pd.DataFrame, pd.Series]:
    """Load features and labels.

    Returns
    -------
    df_data : pd.DataFrame
        Feature matrix with float32 dtype.
    s_label : pd.Series
        Integer label vector.
    """
    df = pd.read_csv(data_path, dtype=np.float32)
    s = pd.read_csv(label_path, header=0).squeeze("columns").astype(np.int32)
    if len(df) != len(s):
        raise ValueError(f"Row count mismatch: {len(df)} vs {len(s)}")
    return df, s


def load_masks(mask_dir: pathlib.Path, n_rows: int) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Load train/val/test boolean masks and verify shape and disjointness."""
    train = np.load(mask_dir / "train_mask.npy")
    val = np.load(mask_dir / "val_mask.npy")
    test = np.load(mask_dir / "test_mask.npy")
    for name, arr in zip(["train", "val", "test"], [train, val, test]):
        if arr.shape != (n_rows,):
            raise ValueError(f"{name}_mask shape {arr.shape} does not match rows {n_rows}")
        if arr.dtype != bool:
            raise ValueError(f"{name}_mask dtype {arr.dtype} is not bool")
    # Ensure masks are disjoint and cover all rows
    if not (np.all(np.logical_not(np.logical_and(train, val))) and
            np.all(np.logical_not(np.logical_and(train, test))) and
            np.all(np.logical_not(np.logical_and(val, test)))):
        raise ValueError("Masks overlap – they must be disjoint")
    if not np.all(train | val | test):
        raise ValueError("Masks do not cover all rows")
    return train, val, test


def data_type_summary(df: pd.DataFrame) -> str:
    types = Counter(str(dt) for dt in df.dtypes)
    return ", ".join(f"{cnt} × {typ}" for typ, cnt in types.items())


def missing_inf_counts(df: pd.DataFrame) -> Tuple[int, int]:
    missing = int(df.isna().sum().sum())
    inf = int(np.isinf(df.values).sum())
    return missing, inf


def constant_features(df: pd.DataFrame) -> List[str]:
    return [col for col in df.columns if df[col].nunique() == 1]


def near_constant_features(df: pd.DataFrame, threshold: float = 0.99) -> List[Tuple[str, float]]:
    """Features where a single value accounts for >= threshold of rows."""
    near_const = []
    n = len(df)
    for col in df.columns:
        top_freq = df[col].value_counts().iloc[0]
        if top_freq / n >= threshold:
            near_const.append((col, top_freq / n))
    return near_const


def descriptive_stats(df: pd.DataFrame) -> pd.DataFrame:
    """Return a compact table with mean, std, min, max for each feature."""
    desc = df.agg(["mean", "std", "min", "max"]).transpose()
    desc.columns = ["Mean", "Std", "Min", "Max"]
    return desc


def extreme_values(df: pd.DataFrame, top_n: int = 3) -> pd.DataFrame:
    """Rows with extreme low/high values per feature (concatenated)."""
    rows = []
    for col in df.columns:
        rows.extend(df[col].nsmallest(top_n).index.tolist())
        rows.extend(df[col].nlargest(top_n).index.tolist())
    rows = sorted(set(rows))
    return df.loc[rows]


def highly_correlated(df: pd.DataFrame, corr_thresh: float = 0.95) -> List[Tuple[str, str, float]]:
    """Return list of (feat_a, feat_b, corr) where |corr| > thresh and a < b."""
    corr_mat = df.corr().abs()
    np.fill_diagonal(corr_mat.values, 0)
    pairs = []
    cols = df.columns
    for i in range(len(cols)):
        for j in range(i + 1, len(cols)):
            val = corr_mat.iat[i, j]
            if val > corr_thresh:
                pairs.append((cols[i], cols[j], val))
    pairs.sort(key=lambda x: -x[2])
    return pairs


def feature_name_checks(df: pd.DataFrame) -> List[str]:
    """Heuristic detection of potentially leaking identifiers in column names."""
    suspicious = []
    for col in df.columns:
        lowered = col.lower()
        if any(tok in lowered for tok in ["id", "ip", "port", "timestamp", "time"]):
            suspicious.append(col)
    return suspicious


def detect_conflicting_groups(df: pd.DataFrame, labels: pd.Series) -> pd.DataFrame:
    """Identify duplicate‑feature groups that contain more than one distinct label."""
    group_ids = df.apply(lambda row: tuple(row.values), axis=1).factorize(sort=True)[0]
    temp = pd.DataFrame({"group_id": group_ids, "label": labels})
    agg = (
        temp.groupby("group_id")
        .agg({"label": lambda x: tuple(sorted(set(x))), "group_id": "size"})
        .rename(columns={"group_id": "size", "label": "label_set"})
    )
    agg["conflict"] = agg["label_set"].apply(lambda s: len(s) > 1)
    return agg[agg["conflict"]]


def write_report(report_path: pathlib.Path, **kw) -> None:
    """Write a markdown report summarising the diagnostics.
    Expected keys in ``kw`` are the individual tables / strings.
    """
    with open(report_path, "w", encoding="utf-8") as f:
        f.write("# SentinelAI – Feature Inspection Report (Phase 2)\n\n")
        f.write(f"**Generated:** {pd.Timestamp.now(tz='UTC')} UTC\n\n")
        # 1. Types / missing / inf
        f.write("## 1. Data Types & Missing/Infinite Values\n\n")
        f.write(f"* Types: {kw['type_summary']}\n")
        f.write(f"* Missing values: {kw['missing']}\n")
        f.write(f"* Infinite values: {kw['infinite']}\n\n")
        # 2. Constant / near‑constant
        f.write("## 2. Constant & Near‑Constant Features\n\n")
        const = kw['constant']
        f.write(f"* Constant features ({len(const)}): {', '.join(const) if const else 'None'}\n")
        near = kw['near_constant']
        f.write(f"* Near‑constant (>99% same) ({len(near)}):\n")
        for col, frac in near:
            f.write(f"  - {col}: {frac:.2%} of rows\n")
        f.write("\n")
        # 3. Descriptive stats
        f.write("## 3. Descriptive Statistics (mean, std, min, max)\n\n")
        desc = kw['desc_stats'].sort_values(by='Std', ascending=False)
        f.write(desc.head(15).to_markdown() + "\n\n")
        # 4. Extreme values
        f.write("## 4. Sample of Extreme Values (top 3 low & high per feature)\n\n")
        f.write(kw['extreme'].head(20).to_markdown() + "\n\n")
        # 5. Highly correlated pairs
        f.write("## 5. Highly Correlated Feature Pairs (|ρ| > 0.95)\n\n")
        corr = kw['high_corr']
        if corr:
            f.write("| Feature A | Feature B | |ρ| |\n|---|---|---|\n")
            for a, b, v in corr:
                f.write(f"| {a} | {b} | {v:.3f} |\n")
            f.write("\n")
        else:
            f.write("*No pairs exceed the threshold.*\n\n")
        # 6. Feature‑name checks
        f.write("## 6. Feature‑Name Leakage Checks\n\n")
        suspect = kw['suspicious_names']
        if suspect:
            f.write("Potential identifier‑like column names detected:\n\n")
            for col in suspect:
                f.write(f"- {col}\n")
            f.write("\nThese should be reviewed for possible removal or anonymisation.\n\n")
        else:
            f.write("No obvious identifier‑like column names found.\n\n")
        # 7. Conflicting‑label groups
        f.write("## 7. Conflicting‑Label Duplicate Groups\n\n")
        conflict_df = kw['conflict_df']
        f.write(f"* Groups with conflicting labels: {conflict_df.shape[0]}\n")
        f.write(f"* Total affected rows: {conflict_df['size'].sum():,}\n\n")
        if not conflict_df.empty:
            f.write("### Example groups (up to 5)\n\n")
            for gid, row in conflict_df.head(5).iterrows():
                f.write(f"- group_id `{gid}` – size {row['size']}, labels {row['label_set']}\n")
            f.write("\n")
        # 8. Preprocessing strategy
        f.write("## 8. Proposed Preprocessing Strategy\n\n")
        f.write(kw['preprocess_strategy'] + "\n\n")
        # 9. Baseline model recommendation
        f.write("## 9. Baseline Model Recommendation\n\n")
        f.write(kw['baseline_recommendation'] + "\n\n")


def main() -> None:
    project_root = pathlib.Path(__file__).resolve().parents[1]
    data_path = project_root / "data" / "raw" / "Data.csv"
    label_path = project_root / "data" / "raw" / "Label.csv"
    mask_dir = project_root / "data" / "processed"
    report_path = project_root / "reports" / "feature_analysis.md"

    df, s = load_data(data_path, label_path)
    n_rows = len(df)
    train_mask, val_mask, test_mask = load_masks(mask_dir, n_rows)

    type_summary = data_type_summary(df)
    missing, infinite = missing_inf_counts(df)
    const = constant_features(df)
    near_const = near_constant_features(df, threshold=0.99)
    desc = descriptive_stats(df)
    extreme = extreme_values(df, top_n=3)
    high_corr = highly_correlated(df, corr_thresh=0.95)
    suspicious = feature_name_checks(df)
    conflict_df = detect_conflicting_groups(df, s)

    preprocess = (
        "We will fit all transformations on the training partition only: "
        "* Impute missing values (none present) and clip extreme outliers based on training‑only quantiles. "
        "* Drop constant features; near‑constant features may be evaluated for removal after impact analysis. "
        "* Apply a robust scaler (e.g., StandardScaler with `with_mean=False`) fitted on training data. "
        "* Encode labels as integer categories (already the case). "
        "* Validation and test sets remain untouched until after the scaler is fitted."
    )

    baseline = (
        "A simple baseline such as multinomial Logistic Regression or a Linear SVM works well for high‑dimensional numeric data. "
        "These models require feature scaling, which the above scaler will provide."
    )

    write_report(
        report_path,
        type_summary=type_summary,
        missing=missing,
        infinite=infinite,
        constant=const,
        near_constant=near_const,
        desc_stats=desc,
        extreme=extreme,
        high_corr=high_corr,
        suspicious_names=suspicious,
        conflict_df=conflict_df,
        preprocess_strategy=preprocess,
        baseline_recommendation=baseline,
    )
    print(f"Report written to {report_path}")


if __name__ == "__main__":
    main()
