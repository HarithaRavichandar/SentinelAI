client = TestClient(app)


def _load_sample_payload():
    fixture_path = Path(__file__).parent / "fixtures" / "sample_features.json"
    with open(fixture_path, "r", encoding="utf-8") as f:
        return json.load(f)


@pytest.fixture(autouse=True)
def clean_environment():
    """Ensure environment is cleanly restored after each test."""
    original_env = os.environ.copy()
    yield
    os.environ.clear()
    os.environ.update(original_env)


def test_triage_groq_success_attribution(monkeypatch):
    """Verify successful Groq explanation reports source='groq' and correct provenance."""
    os.environ["LLM_PROVIDER"] = "groq"
    os.environ["GROQ_API_KEY"] = "gsk_test_mock_key"
    os.environ["GROQ_MODEL"] = "llama-3.3-70b-versatile"

    monkeypatch.setattr(
        "sentinelai.triage.llm_client.get_explanation",
        lambda cid, label, probs: "Explanation generated by Groq LLM.",
    )

    payload = _load_sample_payload()
    response = client.post("/triage", json=payload)
    assert response.status_code == 200
    data = response.json()

    assert data["explanation"] == "Explanation generated by Groq LLM."
    assert data["explanation_source"] == "groq"
    assert "explanation_provenance" in data
    prov = data["explanation_provenance"]
    assert prov["source"] == "groq"
    assert prov["is_llm"] is True
    assert prov["provider"] == "groq"
    assert prov["label"] == "Generated by Groq"
    # Ensure sensitive credentials are never exposed
    assert "gsk_test_mock_key" not in json.dumps(data)


