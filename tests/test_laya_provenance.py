def test_provenance_builder_safeguards():
    """Verify provenance builder handles all edge cases and avoids false attribution."""
    # Template & placeholder aliases
    prov_tmpl = build_explanation_provenance("template")
    assert prov_tmpl == {
        "source": "template",
        "is_llm": False,
        "provider": None,
        "label": "Template explanation",
    }

    prov_legacy = build_explanation_provenance("placeholder")
    assert prov_legacy == {
        "source": "template",
        "is_llm": False,
        "provider": None,
        "label": "Template explanation",
    }

    # Unknown or arbitrary values
    prov_unknown = build_explanation_provenance("unverified_provider")
    assert prov_unknown["is_llm"] is False
    assert prov_unknown["provider"] is None
    assert prov_unknown["label"] is None

    prov_none = build_explanation_provenance("")
    assert prov_none["is_llm"] is False
    assert prov_none["label"] is None


def test_api_response_backward_compatibility():
    """Verify that existing required fields and decision structures are 100% preserved."""
    payload = _load_sample_payload()
    response = client.post("/triage", json=payload)
    assert response.status_code == 200
    data = response.json()

    # Core prediction fields
    assert "class_id" in data
    assert "class_label" in data
    assert "probabilities" in data
    assert isinstance(data["probabilities"], dict)

    # Explanation fields
    assert "explanation" in data
    assert "explanation_source" in data
    assert "explanation_provenance" in data

    # Triage decision engine separation (Laya explanation does not alter decision engine)
    assert "decision" in data
    decision = data["decision"]
    assert "priority" in decision
    assert "decision_status" in decision
    assert "recommended_action" in decision
    assert "decision_confidence" in decision
    assert "policy_mode" in decision
    assert decision["policy_mode"] == "legacy"

